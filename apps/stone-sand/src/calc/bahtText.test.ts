import { bahtText } from './bahtText';

describe('bahtText', () => {
  it.each([
    [0, 'ศูนย์บาทถ้วน'],
    [1, 'หนึ่งบาทถ้วน'],
    [11, 'สิบเอ็ดบาทถ้วน'],
    [21, 'ยี่สิบเอ็ดบาทถ้วน'],
    [101, 'หนึ่งร้อยเอ็ดบาทถ้วน'],
    [220, 'สองร้อยยี่สิบบาทถ้วน'],
    [1500, 'หนึ่งพันห้าร้อยบาทถ้วน'],
    [11875, 'หนึ่งหมื่นหนึ่งพันแปดร้อยเจ็ดสิบห้าบาทถ้วน'],
    [1000000, 'หนึ่งล้านบาทถ้วน'],
    [1000001, 'หนึ่งล้านเอ็ดบาทถ้วน'],
    [21500000, 'ยี่สิบเอ็ดล้านห้าแสนบาทถ้วน'],
  ])('%d → %s', (n, text) => {
    expect(bahtText(n)).toBe(text);
  });

  it('reads satang', () => {
    expect(bahtText(776.87)).toBe('เจ็ดร้อยเจ็ดสิบหกบาทแปดสิบเจ็ดสตางค์');
    expect(bahtText(0.5)).toBe('ห้าสิบสตางค์');
    expect(bahtText(10.01)).toBe('สิบบาทหนึ่งสตางค์');
  });
});
